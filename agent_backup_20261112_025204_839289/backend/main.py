@app.post('/api/agent/analyze')
def analyze_case(data: AgentInput, x_session_id: str = Header(..., alias='X-Session-ID')):
    session_id = require_session_id(x_session_id)
    record = get_owned_record(data.history_id, session_id)
    rows = json.loads(record.inputs_json)
    if data.row_index >= len(rows):
        raise HTTPException(status_code=422, detail='Không tìm thấy mẫu trong lượt dự đoán này.')
    if not data.question.strip():
        raise HTTPException(status_code=422, detail='Câu hỏi trống hoặc lịch sử câu hỏi quá dài.')
    validate_rows([rows[data.row_index]])
    if not agent_slots.acquire(blocking=False):
        raise HTTPException(status_code=429, detail='Trợ lý đang xử lý các ca khác. Vui lòng thử lại sau.')
    try:
        result = get_case_agent().run(rows[data.row_index], data.question.strip(), [m.model_dump() for m in data.conversation])
        return {**result, 'history_id': record.id, 'row_index': data.row_index}
    except (ValueError, OSError, KeyError):
        raise HTTPException(status_code=503, detail='Không tải được công cụ Agent hoặc kho tài liệu. Kiểm tra cấu hình backend.')
    finally:
        agent_slots.release()


@app.post("/api/notify/email")
def notify_email(
    data: EmailNotifyInput,
    x_session_id: str = Header(..., alias="X-Session-ID"),
):
    session_id = require_session_id(x_session_id)
    recipient = data.recipient_email.strip()
    if not re.fullmatch(r"[^\s@]+@[^\s@]+\.[^\s@]+", recipient):
        raise HTTPException(status_code=422, detail="Dia chi email khong hop le")
    record = get_owned_record(data.history_id, session_id)
    subject = "BreastCare AI - Ket qua du doan hoc may"
    send_email(recipient, subject, notification_summary(record))
    return {"sent": True, "message": f"Da gui ket qua toi {recipient}"}


