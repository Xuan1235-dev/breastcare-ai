@app.get("/api/random-sample")
def random_sample(exclude_id: int | None = Query(default=None, ge=1)):
    size = len(dataset)
    if size == 0:
        raise HTTPException(status_code=404, detail="Dataset trong")
    if exclude_id is not None and 1 <= exclude_id <= size and size > 1:
        pos = int(np.random.default_rng().integers(0, size - 1))
        if pos >= exclude_id - 1:
            pos += 1
    else:
        pos = int(np.random.default_rng().integers(0, size))
    row = dataset.iloc[pos]
    return {
        "sample_id": pos + 1,
        "values": [float(row[f]) for f in features],
        "total_samples": size,
        "message": "Mau tham khao tu WDBC; nhan goc khong duoc tiet lo.",
    }


@app.get("/api/random-batch")
def random_batch(count: int = Query(default=100, ge=1, le=100)):
    size = len(dataset)
    if count > size:
        raise HTTPException(status_code=400, detail="So mau vuot qua kich thuoc dataset")
    positions = np.random.default_rng().choice(size, size=count, replace=False).tolist()
    selected = dataset.iloc[positions]
    return {
        "rows": selected.loc[:, features].astype(float).values.tolist(),
        "sample_ids": [int(i) + 1 for i in positions],
        "count": count,
        "total_samples": size,
    }


@app.get("/api/history")
def get_history(
    x_session_id: str = Header(..., alias="X-Session-ID"),
    limit: int = Query(default=50, ge=1, le=100),
):
    session_id = require_session_id(x_session_id)
    with SessionLocal() as db:
        records = db.query(PredictionHistory).filter(
            PredictionHistory.session_id == session_id
        ).order_by(desc(PredictionHistory.created_at)).limit(limit).all()
        return {"items": [record_to_dict(record) for record in records], "total": len(records)}


