@app.post("/api/predict")
def predict(
    data: PredictionInput,
    x_session_id: str = Header(..., alias="X-Session-ID"),
):
    session_id = require_session_id(x_session_id)
    outputs = infer([data.values])
    history_id = save_history(session_id, "individual", [data.values], outputs)
    return {**outputs[0], "history_id": history_id, "created_at": datetime.now(timezone.utc).isoformat()}


@app.post("/api/predict-batch")
def predict_batch(
    data: BatchInput,
    x_session_id: str = Header(..., alias="X-Session-ID"),
):
    session_id = require_session_id(x_session_id)
    validate_rows(data.rows)
    outputs = infer(data.rows)
    history_id = save_history(session_id, "batch", data.rows, outputs)
    malignant_count = sum(1 for item in outputs if item["prediction_code"] == "malignant")
    return {
        "items": outputs,
        "total": len(outputs),
        "malignant_count": malignant_count,
        "benign_count": len(outputs) - malignant_count,
        "history_id": history_id,
        "created_at": datetime.now(timezone.utc).isoformat(),
    }


