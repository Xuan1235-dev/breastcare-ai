def require_session_id(value: str) -> str:
    try:
        return str(UUID(value))
    except (ValueError, TypeError, AttributeError):
        raise HTTPException(status_code=400, detail="Session ID khong hop le. Hay tai lai trang web.")


def validate_rows(rows: list[list[float]]) -> None:
    for i, row in enumerate(rows, start=1):
        if len(row) != len(features):
            raise HTTPException(status_code=422, detail=f"Mau {i} phai co dung {len(features)} dac trung")
        if not all(math.isfinite(float(value)) for value in row):
            raise HTTPException(status_code=422, detail=f"Mau {i} co gia tri rong hoac khong huu han")


def infer(rows: list[list[float]]) -> list[dict[str, Any]]:
    validate_rows(rows)
    frame = pd.DataFrame(rows, columns=features)
    probabilities = model.predict_proba(frame)[:, malignant_class_index]
    output = []
    for probability in probabilities:
        p = float(probability)
        output.append({
            "prediction": "Ác tính" if p >= threshold else "Lành tính",
            "prediction_code": "malignant" if p >= threshold else "benign",
            "malignant_probability": p,
            "threshold": threshold,
            "model": model_name,
            "disclaimer": DISCLAIMER,
        })
    return output


def save_history(
    session_id: str,
    mode: str,
    inputs: list[list[float]],
    outputs: list[dict[str, Any]],
) -> str:
    history_id = str(uuid4())
    malignant_count = sum(1 for item in outputs if item["prediction_code"] == "malignant")
    record = PredictionHistory(
        id=history_id,
        session_id=session_id,
        mode=mode,
        created_at=datetime.now(timezone.utc).isoformat(),
        model_name=model_name,
        threshold=threshold,
        total=len(outputs),
        malignant_count=malignant_count,
        benign_count=len(outputs) - malignant_count,
        inputs_json=json.dumps(inputs, ensure_ascii=False),
        results_json=json.dumps(outputs, ensure_ascii=False),
    )
    try:
        with SessionLocal() as db:
            db.add(record)
            db.commit()
    except Exception as exc:
        raise HTTPException(status_code=503, detail=f"Khong the luu lich su vao co so du lieu: {exc.__class__.__name__}")
    return history_id


def record_to_dict(record: PredictionHistory) -> dict[str, Any]:
    return {
        "id": record.id,
        "mode": record.mode,
        "created_at": record.created_at,
        "model_name": record.model_name,
        "threshold": record.threshold,
        "total": record.total,
        "malignant_count": record.malignant_count,
        "benign_count": record.benign_count,
        "results": json.loads(record.results_json),
    }


def get_owned_record(history_id: str, session_id: str) -> PredictionHistory:
    try:
        normalized_id = str(UUID(history_id))
    except (ValueError, TypeError, AttributeError):
        raise HTTPException(status_code=400, detail="Ma lich su khong hop le")
    with SessionLocal() as db:
        record = db.query(PredictionHistory).filter(
            PredictionHistory.id == normalized_id,
            PredictionHistory.session_id == session_id,
        ).first()
        if record is None:
            raise HTTPException(status_code=404, detail="Khong tim thay ban ghi trong phien nay")
        # Return a detached copy; scalar fields remain available after session closes.
        db.expunge(record)
        return record


def notification_summary(record: PredictionHistory) -> str:
    mode_text = "Dự đoán cá nhân" if record.mode == "individual" else "Dự đoán hàng loạt"
    lines = [
        "BREASTCARE AI - KẾT QUẢ THỰC NGHIỆM",
        f"Chức năng: {mode_text}",
        f"Thời gian: {record.created_at or 'Không rõ'}",
        f"Mô hình: {record.model_name}",
        f"Ngưỡng phân loại: {record.threshold:.2f}",
        f"Tổng số mẫu: {record.total}",
        f"Dự đoán ác tính: {record.malignant_count}",
        f"Dự đoán lành tính: {record.benign_count}",
    ]
    results = json.loads(record.results_json)
    if record.mode == "individual" and results:
        lines += [
            f"Kết quả: {results[0]['prediction']}",
            f"Xác suất ác tính do mô hình ước lượng: {results[0]['malignant_probability']:.2%}",
        ]
    elif record.mode == "batch":
        lines.append("Chi tiết tối đa 20 mẫu đầu:")
        for index, item in enumerate(results[:20], start=1):
            lines.append(f"{index}. {item['prediction']} - xác suất ác tính {item['malignant_probability']:.2%}")
        if len(results) > 20:
            lines.append(f"... còn {len(results) - 20} mẫu trong lịch sử trên website.")
    lines += ["", DISCLAIMER]
    return "\n".join(lines)


def send_telegram(message: str) -> None:
    token = os.getenv("TELEGRAM_BOT_TOKEN", "").strip()
    chat_id = os.getenv("TELEGRAM_CHAT_ID", "").strip()
    if not token or not chat_id:
        raise HTTPException(status_code=503, detail="Chua cau hinh TELEGRAM_BOT_TOKEN va TELEGRAM_CHAT_ID tren Backend")
    payload = json.dumps({"chat_id": chat_id, "text": message}).encode("utf-8")
    request = Request(
        f"https://api.telegram.org/bot{token}/sendMessage",
        data=payload,
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    try:
        with urlopen(request, timeout=20) as response:
            body = json.loads(response.read().decode("utf-8"))
            if not body.get("ok"):
                raise HTTPException(status_code=502, detail="Telegram tu choi yeu cau gui tin nhan")
    except HTTPError as exc:
        raise HTTPException(status_code=502, detail=f"Telegram HTTP {exc.code}")
    except URLError:
        raise HTTPException(status_code=502, detail="Backend khong ket noi duoc Telegram")


def send_email(recipient: str, subject: str, body: str) -> None:
    host = os.getenv("SMTP_HOST", "").strip()
    port = int(os.getenv("SMTP_PORT", "587"))
    username = os.getenv("SMTP_USER", "").strip()
    password = os.getenv("SMTP_PASSWORD", "")
    sender = os.getenv("SMTP_FROM", username).strip()
    use_tls = os.getenv("SMTP_USE_TLS", "true").lower() in {"1", "true", "yes", "on"}
    if not host or not sender:
        raise HTTPException(status_code=503, detail="Chua cau hinh SMTP_HOST va SMTP_FROM tren Backend")
    message = EmailMessage()
    message["From"] = sender
    message["To"] = recipient
    message["Subject"] = subject
    message.set_content(body)
    try:
        if port == 465:
            with smtplib.SMTP_SSL(host, port, context=ssl.create_default_context(), timeout=25) as server:
                if username:
                    server.login(username, password)
                server.send_message(message)
        else:
            with smtplib.SMTP(host, port, timeout=25) as server:
                server.ehlo()
                if use_tls:
                    server.starttls(context=ssl.create_default_context())
                    server.ehlo()
                if username:
                    server.login(username, password)
                server.send_message(message)
    except (smtplib.SMTPException, OSError) as exc:
        raise HTTPException(status_code=502, detail=f"Gui email that bai: {exc.__class__.__name__}")


